/** Airline name for a callsign such as "ACA123", or "" when the prefix is unknown. */
export function airlineFromCallsign(callsign: string): string {
  const m = /^([A-Z]{3})\d/.exec(callsign.trim().toUpperCase())
  return m ? (AIRLINES[m[1]] ?? '') : ''
}

export function airlineFromCode(code: string): string {
  return AIRLINES[code.toUpperCase()] ?? ''
}
