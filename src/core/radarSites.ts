export const RADAR_SITES: readonly RadarSite[] = TABLE.map(([id, lat, lon, elevM]) => ({
  id,
  lat,
  lon,
  elevM,
}))

/** Max airport distance from a radar: beyond this the lowest beam is too high to say much about the airport. */
export const RADAR_RANGE_KM = 230
/** How many sites to merge (nearest first). */
export const RADAR_MAX_SITES = 2

/** Sites within range of `p`, nearest first (at most `max`). */
export function radarsFor(p: LatLon, max = RADAR_MAX_SITES): RadarSite[] {
  return RADAR_SITES.map((s) => ({ s, d: distanceNm(p, s) * KM_PER_NM }))
    .filter((x) => x.d <= RADAR_RANGE_KM)
    .sort((a, b) => a.d - b.d)
    .slice(0, max)
    .map((x) => x.s)
}
